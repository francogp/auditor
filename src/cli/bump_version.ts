const BUMP_SUBCOMMAND_NAMES: ReadonlySet<string> = new Set(['analyze', 'bump', 'version', 'help']);

function resolveBumpTypeFromParsed(
  explicitType: string | undefined,
  positionalType: string | undefined
): CliBumpType {
  if (explicitType) {
    const val = explicitType.toLowerCase();
    if (isCliBumpType(val)) {
      return val;
    }
    throw new Error(
      `Unrecognized bump type in --type: "${val}". Valid options: ${CLI_BUMP_TYPES.join(', ')}.`
    );
  }
  if (positionalType) {
    const lowerPos = positionalType.toLowerCase();
    if (isCliBumpType(lowerPos)) {
      return lowerPos;
    }
    throw new Error(
      `Unrecognized bump type: "${positionalType}". Valid options: ${CLI_BUMP_TYPES.join(', ')}.`
    );
  }
  return 'auto';
}

function handleBumpCommand(
  parsed: ReturnType<typeof parseCittyArgs<typeof BUMP_CLI_ARGS>>,
  positionalType: string | undefined,
  isJson: boolean,
  cwd?: string
): void {
  const targetVersion =
    (typeof parsed['target-version'] === 'string' && parsed['target-version']) ||
    (typeof parsed.target === 'string' && parsed.target) ||
    undefined;
  const bumpType = resolveBumpTypeFromParsed(
    typeof parsed.type === 'string' ? parsed.type : undefined,
    positionalType
  );
  const noSyncPublic =
    parsed['sync-public'] === false || Boolean(parsed['no-sync-public']);
  const syncTargets =
    typeof parsed.sync === 'string'
      ? parsed.sync.split(',').filter(Boolean)
      : undefined;

  const result = applyVersionBump({
    bumpType,
    targetVersion,
    autoSyncPublicVersionJson: noSyncPublic ? false : undefined,
    syncTargets,
    cwd
  });

  if (isJson) {
    console.log(JSON.stringify(result, null, 2));
  } else {
    console.log(styleText('green', `[OK] Version updated successfully:`));
    console.log(
      `  ${result.previousVersion} → ${styleText(['bold', 'cyan'], result.newVersion)} (Bump: ${result.bumpType.toUpperCase()})`
    );
    const effectiveCwd = cwd ?? process.cwd();
    const relFiles = result.syncedFiles.map((f) => path.relative(effectiveCwd, f) || f);
    console.log(`  Synchronized files: ${relFiles.join(', ')}\n`);
  }
}

type ParsedBumpArgs = ReturnType<typeof parseCittyArgs<typeof BUMP_CLI_ARGS>>;

function resolveCliCommand(parsed: ParsedBumpArgs): string {
  if (parsed.help) return 'help';
  if (parsed.analyze) return 'analyze';
  if (parsed.bump) return 'bump';
  if (parsed.version) return 'version';
  const sub = typeof parsed.subcommand === 'string' ? parsed.subcommand.toLowerCase() : '';
  if (sub) {
    if (isCliBumpType(sub)) return 'bump';
    return sub;
  }
  return 'version';
}

function resolvePositionalBumpType(parsed: ParsedBumpArgs, command: string): string | undefined {
  const sub = typeof parsed.subcommand === 'string' ? parsed.subcommand.toLowerCase() : undefined;
  const target = typeof parsed.bumpType === 'string' ? parsed.bumpType : undefined;
  if (command === 'bump') {
    if (sub && isCliBumpType(sub)) return sub;
    return target;
  }
  return target;
}

function isJsonRequested(parsed: ParsedBumpArgs): boolean {
  if (parsed.json || parsed.format === 'json') return true;
  return parsed.subcommand === 'json' || parsed.bumpType === 'json';
}

function executeBumpAction(
  parsed: ParsedBumpArgs,
  bumpType: string | undefined,
  isJson: boolean,
  cwd: string
): void {
  try {
    handleBumpCommand(parsed, bumpType, isJson, cwd);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(styleText('red', `[Error] ${message}`));
    process.exitCode = 1;
  }
}

export function runBumpCli(
  rawArgs: readonly string[] = getProcessCliArgs(),
  cwd: string = process.cwd()
): void {
  const parsed = parseCittyArgs(BUMP_CLI_ARGS, rawArgs, BUMP_SUBCOMMAND_NAMES);
  const command = resolveCliCommand(parsed);
  const bumpType = resolvePositionalBumpType(parsed, command);
  const isJson = isJsonRequested(parsed);
  const isHuman = resolveHumanModeFromArgs(parsed);

  switch (command) {
    case 'help':
      printHelp(bumpType);
      break;
    case 'version':
      console.log(
        `@francogp/auditor v${AUDITOR_VERSION} (Build: ${AUDITOR_BUILD_ID}, Date: ${AUDITOR_BUILD_DATE})`
      );
      break;
    case 'analyze':
      handleAnalyzeCommand({ isJson, isHuman });
      break;
    case 'bump':
      executeBumpAction(parsed, bumpType, isJson, cwd);
      break;
    default:
      console.log(`Unknown command: ${command}`);
      printHelp();
      break;
  }
}

if (isMainModule(import.meta.url)) {
  runBumpCli();
}
