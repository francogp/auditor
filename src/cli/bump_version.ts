export interface MetricTableRow {
  readonly label: string;
  readonly value: string;
}

export const CLI_BUMP_TYPES = ['major', 'minor', 'patch', 'build', 'auto'] as const;
export type CliBumpType = (typeof CLI_BUMP_TYPES)[number];
const CLI_BUMP_TYPE_SET: ReadonlySet<string> = new Set<string>(CLI_BUMP_TYPES);

// type guard predicate for CliBumpType
export function isCliBumpType(val: string): val is CliBumpType {
  return CLI_BUMP_TYPE_SET.has(val);
}

export interface ApplyBumpOptions {
  cwd?: string;
  bumpType?: CliBumpType;
  targetVersion?: string;
  commitMessage?: string;
  versionTsPath?: string;
  customNow?: Temporal.ZonedDateTime;
  autoSyncPublicVersionJson?: boolean;
  syncTargets?: readonly (string | AuditVersionTargetConfig)[];
}

export interface ApplyBumpResult {
  previousVersion: string;
  newVersion: string;
  bumpType: VersionBumpType;
  buildId: string;
  buildDate: string;
  packageJsonPath: string;
  versionTsPath: string;
  syncedFiles: string[];
}

function updatePackageJsonVersion(
  pkgPath: string,
  newVersion: string
): { previousVersion: string; isAuditorPackage: boolean } {
  const rawPkg = fs.readFileSync(pkgPath, 'utf-8');
  const pkg = JSON.parse(rawPkg) as { name?: string; version?: string };
  const previousVersion = pkg.version ?? '1.0.0';
  pkg.version = newVersion;
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`, 'utf-8');
  return { previousVersion, isAuditorPackage: pkg.name === '@francogp/auditor' };
}

function syncAuditorVersionTs(
  cwd: string,
  customTsPath: string | undefined,
  isAuditorPackage: boolean,
  newVersion: string,
  buildId: string,
  buildDate: string
): string | null {
  if (!customTsPath && !isAuditorPackage) {
    return null;
  }
  const targetVersionTs = customTsPath
    ? path.resolve(cwd, customTsPath)
    : path.resolve(cwd, 'src/core/version.ts');

  const versionTsContent = `/**
 * Single Source of Truth for @francogp/auditor version and build metadata.
 * Automatically generated by auditor-version during compilation.
 */
export const AUDITOR_VERSION = '${newVersion}';
export const AUDITOR_BUILD_ID = '${buildId}';
export const AUDITOR_BUILD_DATE = '${buildDate}';
`;

  return tryOrNull(() => {
    fs.mkdirSync(path.dirname(targetVersionTs), { recursive: true });
    fs.writeFileSync(targetVersionTs, versionTsContent, 'utf-8');
    return targetVersionTs;
  });
}

function resolveNormalizedSyncTargets(
  cwd: string,
  options: ApplyBumpOptions,
  auditConfig: AuditEngineConfig | null
): AuditVersionTargetConfig[] {
  const configTargets = options.syncTargets ?? auditConfig?.version?.syncTargets ?? [];
  const normalizedTargets: AuditVersionTargetConfig[] = configTargets.map((t) =>
    typeof t === 'string' ? { path: t } : t
  );

  const shouldAutoSyncPublic =
    options.autoSyncPublicVersionJson ?? auditConfig?.version?.autoSyncPublicVersionJson ?? true;
  const publicVersionPath = path.resolve(cwd, 'public/version.json');

  if (shouldAutoSyncPublic && fs.existsSync(publicVersionPath)) {
    const alreadyDeclared = normalizedTargets.some(
      (t) => path.resolve(cwd, t.path) === publicVersionPath
    );
    if (!alreadyDeclared) {
      normalizedTargets.push({ path: 'public/version.json' });
    }
  }
  return normalizedTargets;
}

function syncTsTarget(
  targetAbsPath: string,
  target: AuditVersionTargetConfig,
  newVersion: string,
  buildId: string,
  buildDate: string
): void {
  const exportName = target.tsExportName ?? 'APP_VERSION';
  const tsContent = `/**
 * Version and build metadata automatically synchronized by auditor-version.
 */
export const ${exportName} = '${newVersion}';
export const BUILD_ID = '${buildId}';
export const BUILD_DATE = '${buildDate}';
`;
  fs.mkdirSync(path.dirname(targetAbsPath), { recursive: true });
  fs.writeFileSync(targetAbsPath, tsContent, 'utf-8');
}

function syncJsonTarget(
  targetAbsPath: string,
  target: AuditVersionTargetConfig,
  newVersion: string
): void {
  const jsonField = target.jsonField ?? 'version';
  let jsonObj: Record<string, unknown> = {};
  let startsWithV = false;

  if (fs.existsSync(targetAbsPath)) {
    const rawContent = safeReadFileSync(targetAbsPath);
    if (rawContent) {
      const parsed = safeJsonParse<Record<string, unknown>>(rawContent);
      if (parsed) {
        jsonObj = parsed;
        const currentVal = jsonObj[jsonField];
        if (typeof currentVal === 'string' && currentVal.startsWith('v')) {
          startsWithV = true;
        }
      }
    }
  }

  const usePrefixV = target.prefixV ?? startsWithV;
  const versionValue = usePrefixV
    ? newVersion.startsWith('v')
      ? newVersion
      : `v${newVersion}`
    : newVersion.startsWith('v')
      ? newVersion.slice(1)
      : newVersion;

  jsonObj[jsonField] = versionValue;
  fs.mkdirSync(path.dirname(targetAbsPath), { recursive: true });
  fs.writeFileSync(targetAbsPath, `${JSON.stringify(jsonObj, null, 2)}\n`, 'utf-8');
}

function syncAdditionalTargets(
  cwd: string,
  normalizedTargets: readonly AuditVersionTargetConfig[],
  pkgPath: string,
  targetVersionTs: string,
  newVersion: string,
  buildId: string,
  buildDate: string
): string[] {
  const syncedFiles: string[] = [];
  for (const target of normalizedTargets) {
    const targetAbsPath = path.resolve(cwd, target.path);
    if (targetAbsPath === pkgPath || (targetVersionTs && targetAbsPath === targetVersionTs)) {
      continue;
    }

    const isTs = target.type === 'ts' || target.path.endsWith('.ts');
    const result = tryCatchSync(() => {
      if (isTs) {
        syncTsTarget(targetAbsPath, target, newVersion, buildId, buildDate);
      } else {
        syncJsonTarget(targetAbsPath, target, newVersion);
      }
    });
    if (result.ok) {
      syncedFiles.push(targetAbsPath);
    }
  }
  return syncedFiles;
}

function resolveNextVersionAndBump(
  cwd: string,
  options: ApplyBumpOptions,
  buildId: string
): { newVersion: string; resolvedBump: VersionBumpType } {
  if (options.targetVersion) {
    const rawTarget = options.targetVersion.trim();
    const newVersion = rawTarget.includes('-build.') ? rawTarget : `${rawTarget}-build.${buildId}`;
    const resolvedBump =
      options.bumpType && options.bumpType !== 'auto' ? options.bumpType : 'major';
    return { newVersion, resolvedBump };
  }

  const analysis = analyzeVersionBump({
    cwd,
    commitMessage: options.commitMessage,
    customNow: options.customNow
  });

  const resolvedBump: VersionBumpType =
    !options.bumpType || options.bumpType === 'auto' ? analysis.recommendedBump : options.bumpType;

  const nextBase = calculateNextBaseVersion(analysis.baseVersion, resolvedBump);
  return {
    newVersion: `${nextBase}-build.${buildId}`,
    resolvedBump
  };
}

/**
 * Applies a SemVer bump and persists it to package.json, version.ts, and configured sync targets.
 */
export function applyVersionBump(options: ApplyBumpOptions = {}): ApplyBumpResult {
  const cwd = options.cwd ?? process.cwd();
  const pkgPath = path.join(cwd, 'package.json');

  if (!fs.existsSync(pkgPath)) {
    throw new Error(`package.json not found in ${cwd}`);
  }

  const { buildId, buildDate } = generateBuildId(options.customNow);
  const { newVersion, resolvedBump } = resolveNextVersionAndBump(cwd, options, buildId);

  // Load auditConfig safely if available
  const auditConfig: AuditEngineConfig | null = tryOrNull(() => getAuditConfig(cwd));

  const { previousVersion, isAuditorPackage } = updatePackageJsonVersion(pkgPath, newVersion);
  const syncedVersionTs = syncAuditorVersionTs(
    cwd,
    options.versionTsPath,
    isAuditorPackage,
    newVersion,
    buildId,
    buildDate
  );

  const normalizedTargets = resolveNormalizedSyncTargets(cwd, options, auditConfig);
  const additionalSynced = syncAdditionalTargets(
    cwd,
    normalizedTargets,
    pkgPath,
    syncedVersionTs ?? '',
    newVersion,
    buildId,
    buildDate
  );

  const syncedFiles: string[] = [pkgPath];
  if (syncedVersionTs) {
    syncedFiles.push(syncedVersionTs);
  }
  syncedFiles.push(...additionalSynced);

  const syncedDocs = syncDocumentationVersionReferences(cwd);
  for (const docPath of syncedDocs) {
    if (!syncedFiles.includes(docPath)) {
      syncedFiles.push(docPath);
    }
  }

  return {
    previousVersion,
    newVersion,
    bumpType: resolvedBump,
    buildId,
    buildDate,
    packageJsonPath: pkgPath,
    versionTsPath: syncedVersionTs ?? '',
    syncedFiles
  };
}

function renderAnalysisTable(analysis: VersionAnalysisResult): void {
  console.log(
    renderBanner(
      'AUDITOR VERSION - HEURISTIC VERSION ANALYSIS',
      `Current Version: ${analysis.currentVersion}  |  Proposed: ${analysis.recommendedBump.toUpperCase()}`
    )
  );

  const rows: MetricTableRow[] = [
    { label: 'Current Version', value: analysis.currentVersion },
    { label: 'Detected SemVer Base', value: analysis.baseVersion },
    {
      label: 'Recommended Bump',
      value: styleText('bold', analysis.recommendedBump.toUpperCase())
    },
    { label: 'Suggested Version', value: styleText(['bold', 'green'], analysis.recommendedVersion) },
    { label: 'MAJOR Candidate', value: analysis.candidates.major },
    { label: 'MINOR Candidate', value: analysis.candidates.minor },
    { label: 'PATCH Candidate (bugfix)', value: analysis.candidates.patch },
    { label: 'BUILD Candidate (no bump)', value: analysis.candidates.build },
    { label: 'Rationale', value: analysis.rationale },
    { label: 'Modified Files', value: String(analysis.metrics.filesChanged) },
    {
      label: 'Insertions / Deletions',
      value: `+${analysis.metrics.insertions} / -${analysis.metrics.deletions} (${analysis.metrics.totalLinesChanged} lines)`
    },
    {
      label: 'Subsystem Impact',
      value: `Core: ${analysis.metrics.hasCoreChanges ? 'YES' : 'NO'} | New suites/skills: ${analysis.metrics.hasNewFeatures ? 'YES' : 'NO'}`
    }
  ];

  const columns: TableColumn<MetricTableRow>[] = [
    { header: 'METRIC / PARAMETER', width: 28, render: (r: MetricTableRow) => r.label },
    { header: 'EVALUATED DETAIL', width: 46, render: (r: MetricTableRow) => r.value }
  ];

  console.log(renderBoxTable(columns, rows));
  console.log();
}

