export function getCanonicalLanguageMandateSnippet(language: DocumentationLanguage = 'en'): string {
  return CANONICAL_LANGUAGE_MANDATES[language] ?? CANONICAL_LANGUAGE_MANDATES.en;
}

/**
 * Checks if a markdown block contains the canonical language governance mandate.
 */
export function containsLanguageMandate(
  text: string,
  expectedLanguage?: DocumentationLanguage
): boolean {
  const hasSuiteRef =
    /validate_documentation_language|documentation\?\.language|config\.documentation/i.test(text);
  const hasLangTerm = /language|idioma/i.test(text);
  if (!hasSuiteRef && !hasLangTerm) return false;

  const hasDefaultConcept =
    /default|omisi(?:ó|o)n|duda|doubt|unconditionally|incondicionalmente/i.test(text);
  if (!hasDefaultConcept) return false;

  const hasEnglishMention = /english|ingl(?:é|e)s|'en'/i.test(text);
  if (!hasEnglishMention) return false;

  const hasProposalConcept = /learning_proposal|learn-with-docs|proposals?|propuestas?/i.test(text);
  if (!hasProposalConcept) return false;

  const enTokens = /(?:across|depend|strictly|whenever|default language)/i;
  const esTokens =
    /(?:aplicaciones|gobernadas|dependen|estrictamente|propuestas|idioma por defecto)/i;
  return matchesMandateLanguage(text, expectedLanguage, enTokens, esTokens);
}

