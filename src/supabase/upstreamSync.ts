/**
 * src/supabase/upstreamSync.ts
 *
 * Upstream-first sparse clone and Compose metadata inspector for `github.com/supabase/supabase`.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

import { parseDocument } from 'yaml';

import { safeReadFile, safeResolve, safeWriteFile } from '../core/safePath.ts';
import type { SupabaseDockerConfig, SupabaseUpstreamMetadata } from './supabaseConfigTypes.ts';

const UPSTREAM_SUPABASE_REPO = 'https://github.com/supabase/supabase.git' as const;
const LEADING_MAJOR_REGEX = /^v?(\d+)/u;

/**
 * Extracts the leading major integer from Docker image tags (including 4-part tags like `17.6.1.136`).
 */
export function parsePostgresMajorVersion(imageTag: string): number {
  const cleaned = imageTag.trim();
  const match = LEADING_MAJOR_REGEX.exec(cleaned);
  if (!match?.[1]) {
    throw new Error(`Unable to parse PostgreSQL major version from tag '${imageTag}'.`);
  }
  const major = Number.parseInt(match[1], 10);
  if (!Number.isFinite(major) || major < 1) {
    throw new Error(`Invalid PostgreSQL major version '${match[1]}' in tag '${imageTag}'.`);
  }
  return major;
}

/**
 * Inspects an upstream Supabase `docker-compose.yml` via YAML AST to extract image tags.
 */
export function inspectUpstreamCompose(composeYaml: string): SupabaseUpstreamMetadata {
  const doc = parseDocument(composeYaml);
  const rawDbImage = doc.getIn(['services', 'db', 'image']);
  const rawRestImage = doc.getIn(['services', 'rest', 'image']);
  const dbImage = typeof rawDbImage === 'string' ? rawDbImage.trim() : '';
  const restImage = typeof rawRestImage === 'string' ? rawRestImage.trim() : '';
  const hasApiGw = Boolean(doc.getIn(['services', 'api-gw']));
  const gatewayService = hasApiGw ? 'api-gw' : 'kong';

  if (!dbImage) {
    throw new Error('Upstream docker-compose.yml is missing services.db.image.');
  }

  const colonIdx = dbImage.lastIndexOf(':');
  const postgresTag = colonIdx >= 0 ? dbImage.slice(colonIdx + 1) : '';
  if (!postgresTag) {
    throw new Error(`Upstream services.db.image '${dbImage}' is missing an explicit tag.`);
  }

  return {
    postgresImage: dbImage,
    postgresTag,
    postgresMajor: parsePostgresMajorVersion(postgresTag),
    postgrestImage: restImage,
    gatewayService
  };
}

/**
 * Generates the custom PostgreSQL `Dockerfile` packaging project `init/` SQL scripts and upstream assets.
 */
export function generateCustomDbDockerfile(postgresImage: string, projectSlug: string): string {
  return [
    `# ${projectSlug} — Custom Supabase PostgreSQL Image (generated by @francogp/auditor/supabase)`,
    `FROM ${postgresImage}`,
    '',
    'LABEL org.opencontainers.image.title="supabase-postgres-custom"',
    `LABEL com.francogp.auditor.project="${projectSlug}"`,
    '',
    '# Project-specific first-boot SQL init scripts',
    'COPY init/ /docker-entrypoint-initdb.d/',
    '',
    '# Official upstream DB initialization & migration scripts',
    'COPY volumes/db/realtime.sql /docker-entrypoint-initdb.d/migrations/99-realtime.sql',
    'COPY volumes/db/webhooks.sql /docker-entrypoint-initdb.d/init-scripts/98-webhooks.sql',
    'COPY volumes/db/roles.sql /docker-entrypoint-initdb.d/init-scripts/99-roles.sql',
    'COPY volumes/db/jwt.sql /docker-entrypoint-initdb.d/init-scripts/99-jwt.sql',
    'COPY volumes/db/_supabase.sql /docker-entrypoint-initdb.d/migrations/97-_supabase.sql',
    'COPY volumes/db/logs.sql /docker-entrypoint-initdb.d/migrations/99-logs.sql',
    'COPY volumes/db/pooler.sql /docker-entrypoint-initdb.d/migrations/99-pooler.sql',
    '',
    '# Packaged configuration assets synced into <volumes.shared> by supabase-config-init',
    'COPY volumes/api /supabase-volumes/api',
    'COPY volumes/pooler /supabase-volumes/pooler',
    'COPY volumes/functions /supabase-volumes/functions',
    'COPY volumes/snippets /supabase-volumes/snippets',
    'COPY volumes/realtime /supabase-volumes/realtime',
    'COPY volumes/logs /supabase-volumes/logs',
    '',
    'RUN mkdir -p /etc/postgresql-custom/conf.d && chown -R postgres:postgres /etc/postgresql-custom',
    ''
  ].join('\n');
}

/**
 * Performs a clean sparse clone of `supabase/supabase` `docker/` at `upstreamRef` and emits `Dockerfile`.
 */
export async function cloneUpstreamSupabaseDocker(
  projectRoot: string,
  config: SupabaseDockerConfig,
  refOverride?: string
): Promise<SupabaseUpstreamMetadata> {
  const targetRef = refOverride?.trim() || config.upstreamRef;
  const supabaseDir = safeResolve(projectRoot, config.supabaseDir);
  const dockerDir = path.join(supabaseDir, 'docker');
  const tempCloneDir = path.join(supabaseDir, '.tmp-upstream-clone');

  await fs.promises.rm(tempCloneDir, { recursive: true, force: true });
  await fs.promises.mkdir(supabaseDir, { recursive: true });

  execFileSync(
    'git',
    [
      'clone',
      '--depth',
      '1',
      '--branch',
      targetRef,
      '--filter=blob:none',
      '--sparse',
      UPSTREAM_SUPABASE_REPO,
      tempCloneDir
    ],
    { cwd: projectRoot, stdio: 'inherit' }
  );
  execFileSync('git', ['sparse-checkout', 'set', 'docker'], {
    cwd: tempCloneDir,
    stdio: 'inherit'
  });

  await fs.promises.rm(dockerDir, { recursive: true, force: true });
  await fs.promises.rename(path.join(tempCloneDir, 'docker'), dockerDir);
  await fs.promises.rm(tempCloneDir, { recursive: true, force: true });

  const composeContent = await safeReadFile(path.join(dockerDir, 'docker-compose.yml'));
  const metadata = inspectUpstreamCompose(composeContent);

  await fs.promises.mkdir(path.join(dockerDir, 'init'), { recursive: true });
  const dockerfile = generateCustomDbDockerfile(metadata.postgresImage, config.projectSlug);
  await safeWriteFile(path.join(dockerDir, 'Dockerfile'), dockerfile);

  return metadata;
}
