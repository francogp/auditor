/**
 * src/supabase/upstreamSync.ts
 *
 * Upstream-first sparse clone and Compose metadata inspector for `github.com/supabase/supabase`.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

import { parseDocument } from 'yaml';

import { safeReadFile, safeResolve, safeWriteFile } from '../core/safePath.ts';
import {
  stampSupabaseSchemaHeader,
  type SupabaseDockerConfig,
  type SupabaseUpstreamMetadata
} from './supabaseConfigTypes.ts';

const UPSTREAM_SUPABASE_REPO = 'https://github.com/supabase/supabase.git' as const;
const LEADING_MAJOR_REGEX = /^v?(\d+)/u;
const GIT_SHA_REGEX = /^[0-9a-f]{7,40}$/iu;

const UPSTREAM_DB_SQL_MAPPINGS: ReadonlyArray<readonly [string, string]> = [
  ['volumes/db/realtime.sql', '/docker-entrypoint-initdb.d/migrations/99-realtime.sql'],
  ['volumes/db/webhooks.sql', '/docker-entrypoint-initdb.d/init-scripts/98-webhooks.sql'],
  ['volumes/db/roles.sql', '/docker-entrypoint-initdb.d/init-scripts/99-roles.sql'],
  ['volumes/db/jwt.sql', '/docker-entrypoint-initdb.d/init-scripts/99-jwt.sql'],
  ['volumes/db/_supabase.sql', '/docker-entrypoint-initdb.d/migrations/97-_supabase.sql'],
  ['volumes/db/logs.sql', '/docker-entrypoint-initdb.d/migrations/99-logs.sql'],
  ['volumes/db/pooler.sql', '/docker-entrypoint-initdb.d/migrations/99-pooler.sql']
];

const DEFAULT_ASSET_VOLUME_DIRS = ['api', 'functions', 'logs', 'pooler', 'snippets'] as const;

/**
 * Extracts the leading major integer from Docker image tags (including 4-part tags like `17.6.1.136`).
 */
export function parsePostgresMajorVersion(imageTag: string): number {
  const cleaned = imageTag.trim();
  const match = LEADING_MAJOR_REGEX.exec(cleaned);
  if (!match?.[1]) {
    throw new Error(`Unable to parse PostgreSQL major version from tag '${imageTag}'.`);
  }
  const major = Number.parseInt(match[1], 10);
  if (!Number.isFinite(major) || major < 1) {
    throw new Error(`Invalid PostgreSQL major version '${match[1]}' in tag '${imageTag}'.`);
  }
  return major;
}

/**
 * Inspects an upstream Supabase `docker-compose.yml` via YAML AST to extract image tags.
 */
export function inspectUpstreamCompose(composeYaml: string): SupabaseUpstreamMetadata {
  const doc = parseDocument(composeYaml);
  const rawDbImage = doc.getIn(['services', 'db', 'image']);
  const rawRestImage = doc.getIn(['services', 'rest', 'image']);
  const dbImage = typeof rawDbImage === 'string' ? rawDbImage.trim() : '';
  const restImage = typeof rawRestImage === 'string' ? rawRestImage.trim() : '';
  const hasApiGw = Boolean(doc.getIn(['services', 'api-gw']));
  const gatewayService = hasApiGw ? 'api-gw' : 'kong';

  if (!dbImage) {
    throw new Error('Upstream docker-compose.yml is missing services.db.image.');
  }

  const colonIdx = dbImage.lastIndexOf(':');
  const postgresTag = colonIdx >= 0 ? dbImage.slice(colonIdx + 1) : '';
  if (!postgresTag) {
    throw new Error(`Upstream services.db.image '${dbImage}' is missing an explicit tag.`);
  }

  return {
    postgresImage: dbImage,
    postgresTag,
    postgresMajor: parsePostgresMajorVersion(postgresTag),
    postgrestImage: restImage,
    gatewayService
  };
}

function resolveDbSqlCopyLines(dockerDir?: string): readonly string[] {
  return UPSTREAM_DB_SQL_MAPPINGS.filter(([srcRel]) =>
    dockerDir ? fs.existsSync(path.join(dockerDir, srcRel)) : true
  ).map(([srcRel, destPath]) => `COPY ${srcRel} ${destPath}`);
}

function resolveAssetVolumeCopyLines(dockerDir?: string): readonly string[] {
  const volumesDir = dockerDir ? path.join(dockerDir, 'volumes') : null;
  if (volumesDir && fs.existsSync(volumesDir)) {
    return fs
      .readdirSync(volumesDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && entry.name !== 'db')
      .map((entry) => entry.name)
      .sort((a, b) => a.localeCompare(b))
      .map((dirName) => `COPY volumes/${dirName} /supabase-volumes/${dirName}`);
  }
  return DEFAULT_ASSET_VOLUME_DIRS.map(
    (dirName) => `COPY volumes/${dirName} /supabase-volumes/${dirName}`
  );
}

/**
 * Generates the custom PostgreSQL `Dockerfile` packaging project `init/` SQL scripts and upstream assets.
 * Inspects `dockerDir` when present so `COPY` statements strictly match existing upstream `volumes/` entries.
 */
export function generateCustomDbDockerfile(
  postgresImage: string,
  projectSlug: string,
  dockerDir?: string
): string {
  return stampSupabaseSchemaHeader(
    [
      `# ${projectSlug} — Custom Supabase PostgreSQL Image (generated by @francogp/auditor/supabase)`,
      `FROM ${postgresImage}`,
      '',
      'LABEL org.opencontainers.image.title="supabase-postgres-custom"',
      `LABEL com.francogp.auditor.project="${projectSlug}"`,
      '',
      '# Project-specific first-boot SQL init scripts',
      'COPY init/ /docker-entrypoint-initdb.d/',
      '',
      '# Official upstream DB initialization & migration scripts',
      ...resolveDbSqlCopyLines(dockerDir),
      '',
      '# Packaged configuration assets synced into <volumes.shared> by supabase-config-init',
      ...resolveAssetVolumeCopyLines(dockerDir),
      '',
      'RUN mkdir -p /etc/postgresql-custom/conf.d && chown -R postgres:postgres /etc/postgresql-custom',
      ''
    ].join('\n')
  );
}

async function syncInitSqlDir(
  projectRoot: string,
  config: SupabaseDockerConfig,
  dockerInitDir: string
): Promise<void> {
  await fs.promises.mkdir(dockerInitDir, { recursive: true });
  const sourceInitRel = config.extensions?.initDir?.trim();
  if (sourceInitRel) {
    const sourceInitDir = safeResolve(projectRoot, sourceInitRel);
    if (fs.existsSync(sourceInitDir)) {
      const entries = await fs.promises.readdir(sourceInitDir, { withFileTypes: true });
      for (const entry of entries) {
        if (!entry.isFile() || !entry.name.endsWith('.sql')) continue;
        await fs.promises.copyFile(
          path.join(sourceInitDir, entry.name),
          path.join(dockerInitDir, entry.name)
        );
      }
    }
  }
  const existing = await fs.promises.readdir(dockerInitDir);
  if (existing.length === 0) {
    await safeWriteFile(path.join(dockerInitDir, '.gitkeep'), '');
  }
}

function setDockerSparseCheckout(cloneDir: string): void {
  execFileSync('git', ['sparse-checkout', 'set', 'docker'], {
    cwd: cloneDir,
    stdio: 'inherit'
  });
}

/**
 * Performs a clean sparse clone of `supabase/supabase` `docker/` at `upstreamRef` inside `scratch/` and emits `Dockerfile`.
 */
export async function cloneUpstreamSupabaseDocker(
  projectRoot: string,
  config: SupabaseDockerConfig,
  refOverride?: string
): Promise<SupabaseUpstreamMetadata> {
  const targetRef = refOverride?.trim() || config.upstreamRef;
  const supabaseDir = safeResolve(projectRoot, config.supabaseDir);
  const dockerDir = path.join(supabaseDir, 'docker');
  const tempCloneDir = safeResolve(projectRoot, 'scratch', 'supabase-upstream-clone');

  await fs.promises.rm(tempCloneDir, { recursive: true, force: true });
  await fs.promises.mkdir(supabaseDir, { recursive: true });
  await fs.promises.mkdir(path.dirname(tempCloneDir), { recursive: true });

  if (GIT_SHA_REGEX.test(targetRef)) {
    await fs.promises.mkdir(tempCloneDir, { recursive: true });
    execFileSync('git', ['init'], { cwd: tempCloneDir, stdio: 'inherit' });
    execFileSync('git', ['remote', 'add', 'origin', UPSTREAM_SUPABASE_REPO], {
      cwd: tempCloneDir,
      stdio: 'inherit'
    });
    setDockerSparseCheckout(tempCloneDir);
    execFileSync('git', ['fetch', '--depth', '1', 'origin', targetRef], {
      cwd: tempCloneDir,
      stdio: 'inherit'
    });
    execFileSync('git', ['checkout', 'FETCH_HEAD'], { cwd: tempCloneDir, stdio: 'inherit' });
  } else {
    execFileSync(
      'git',
      [
        'clone',
        '--depth',
        '1',
        '--branch',
        targetRef,
        '--filter=blob:none',
        '--sparse',
        UPSTREAM_SUPABASE_REPO,
        tempCloneDir
      ],
      { cwd: projectRoot, stdio: 'inherit' }
    );
    setDockerSparseCheckout(tempCloneDir);
  }

  await fs.promises.rm(dockerDir, { recursive: true, force: true });
  await fs.promises.rename(path.join(tempCloneDir, 'docker'), dockerDir);
  await fs.promises.rm(tempCloneDir, { recursive: true, force: true });

  const composeContent = await safeReadFile(path.join(dockerDir, 'docker-compose.yml'));
  const metadata = inspectUpstreamCompose(composeContent);

  await syncInitSqlDir(projectRoot, config, path.join(dockerDir, 'init'));
  const dockerfile = generateCustomDbDockerfile(
    metadata.postgresImage,
    config.projectSlug,
    dockerDir
  );
  await safeWriteFile(path.join(dockerDir, 'Dockerfile'), dockerfile);

  return metadata;
}
